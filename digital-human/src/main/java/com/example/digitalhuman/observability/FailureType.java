package com.example.digitalhuman.observability;

/**
 * 失败分类（第 17 掌）。
 *
 * <p>文章给的理由很实在：**成功率告诉你「有问题」，失败分类告诉你「问题在哪一类」**。
 * 只统计「失败数」的话，模型超时（可重试）和输入非法（不可重试）会挤在同一个计数器里，
 * 告警响起来也没有人能据此决定做什么。
 *
 * <p>更关键的是它决定了能否定位到层：一次请求会穿过模型、工具、RAG、Graph 节点、远程 Agent，
 * 分类就是「死在某一层」这件事的可聚合表达。分类表在写第一行观测代码时就定下来——
 * 事后补分类意味着所有历史数据都要重跑。
 */
public enum FailureType {

    /** 模型侧超时或不可达：**可重试**。 */
    MODEL_TIMEOUT,
    /** 模型侧拒绝或返回错误（含鉴权失败、空响应）：多数**不可重试**。 */
    MODEL_ERROR,
    /** 工具自身抛出异常或超时：看工具语义决定能否重试。 */
    TOOL_ERROR,
    /** 检索没有命中依据，系统按契约拒答：这是**正常业务行为**，不是故障。 */
    RAG_EMPTY,
    /** 检索/向量库本身出错：基础设施问题。 */
    RAG_ERROR,
    /** 图节点执行失败。 */
    GRAPH_NODE_ERROR,
    /** 跨服务调用远程 Agent 失败。 */
    REMOTE_AGENT_ERROR,
    /** 入参不合法：调用方问题，**不该重试**。 */
    INPUT_INVALID,
    /** 会话正忙（同一会话并发请求）：**可重试**，但要退避。 */
    CONVERSATION_BUSY,
    /** 没有归类到的失败。留这个分类的目的是：它变多就说明分类表该补了。 */
    UNKNOWN
}
